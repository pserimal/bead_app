#!/usr/bin/env python3
"""Build a COLOR dual-domain training set for the RGB CRNN.

Combines:
  1. fresh COLOR board cells (generate_board + crop_board, RGB preserved)
  2. real labeled COLOR cells (training/samples/1_标注结果_2026-07-29)

The old mixed_v11 cells are GRAYSCALE (generated by the pre-color crop
pipeline) so they carry no color signal — this set is built entirely from
color-preserving sources.

Output: training/data/color_dual/<name>/cells/ + manifest.csv
"""
from __future__ import annotations

import argparse
import csv
import random
import shutil
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

from training.models.board_generator import generate_board, save_board  # noqa: E402
from training.scripts.crop_board import crop_board_dir  # noqa: E402


def build(name: str, sources: list[Path], boards_per_source: int,
          board_seed: int, real_dir: Path | None, out_root: Path,
          brand: str = "mard", max_cells: int | None = None) -> dict:
    out = out_root / name
    out.mkdir(parents=True, exist_ok=True)

    # ── 1. Generate COLOR boards + crop to cells ──
    workdir = out / "boards"
    total_cells = 0
    codes_seen: set[str] = set()
    for si, src in enumerate(sources):
        with Image.open(src) as im:
            im.load()
            image = np.array(im.convert("RGB"))
        for bi in range(boards_per_source):
            cols = random.randint(40, 120)
            board = generate_board(
                image, brand=brand, cols=cols, cell_size=48,
                seed=board_seed * 1000 + si * 100 + bi,
            )
            bdir = workdir / f"s{si}_b{bi}"
            save_board(board, bdir)
            res = crop_board_dir(bdir, seed=board_seed + bi)
            if not res.get("ok"):
                print(f"  [warn] board {bdir.name} crop failed: {res.get('reason')}")
                continue
            total_cells += res["cells"]
            bman = bdir / "cells" / "manifest.csv"
            if bman.exists():
                with open(bman, encoding="utf-8-sig") as f:
                    for row in csv.DictReader(f):
                        codes_seen.add(row["编码"])
        print(f"  [board] src {src.stem}: {boards_per_source} boards done")

    # ── 2. Copy real labeled COLOR cells ──
    real_cells = 0
    if real_dir is not None:
        for f in sorted(real_dir.glob("*_marked*.png")):
            code = f.name.split("_")[0]
            if not code or not code[0].isalpha():
                continue
            # 空白格导出为 blank_* (旧导出为 EMPTY_*), 无 OCR 编码含义, 不进入训练集
            if code == "blank" or code == "EMPTY":
                continue
            shutil.copy(f, out / f.name)
            real_cells += 1
            codes_seen.add(code)

    # ── 3. Merge manifests into one CSV at the root ──
    rows: list[dict] = []
    cells_dir = out / "cells"
    cells_dir.mkdir(exist_ok=True)
    # move board-crop cells into cells/ with r.._c.._CODE names already unique
    for bdir in sorted((workdir).glob("s*_b*")):
        bman = bdir / "cells" / "manifest.csv"
        if not bman.exists():
            continue
        with open(bman, encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                src_f = bdir / "cells" / row["文件名"]
                if src_f.exists():
                    shutil.copy(src_f, cells_dir / row["文件名"])
                    rows.append(row)
    # real cells (keep original names)
    if real_dir is not None:
        for f in sorted(out.glob("*_marked*.png")):
            code = f.name.split("_")[0]
            rows.append({"编码": code, "文件名": f.name, "行": "", "列": "",
                         "色相": "", "亮度": ""})
            shutil.copy(f, cells_dir / f.name)
            f.unlink()  # remove from root after move

    # cap if requested (keep distribution roughly)
    if max_cells and len(rows) > max_cells:
        random.seed(0)
        random.shuffle(rows)
        keep = set(r["文件名"] for r in rows[:max_cells])
        rows = [r for r in rows if r["文件名"] in keep]
        # remove files not in keep
        for f in cells_dir.glob("*.png"):
            if f.name not in keep:
                f.unlink()

    manifest_path = out / "manifest.csv"
    with open(manifest_path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["编码", "文件名", "行", "列", "色相", "亮度"])
        writer.writeheader()
        writer.writerows(rows)

    print(f"[done] {out}: {len(rows)} cells, {len(codes_seen)} codes "
          f"(board={total_cells}, real={real_cells})")
    return {"cells": len(rows), "codes": len(codes_seen),
            "board_cells": total_cells, "real_cells": real_cells}


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--name", default="color_dual")
    p.add_argument("--boards-per-source", type=int, default=10)
    p.add_argument("--max-cells", type=int, default=None)
    p.add_argument("--out-root", type=Path,
                   default=_REPO_ROOT / "training" / "data")
    args = p.parse_args()

    sources = [
        _REPO_ROOT / "training" / "samples" / "stand" / f"{i}.jpg"
        for i in range(1, 6)
    ]
    real_dir = _REPO_ROOT / "training" / "samples" / "1_标注结果_2026-07-29"
    build(args.name, sources, args.boards_per_source, board_seed=42,
          real_dir=real_dir, out_root=args.out_root, max_cells=args.max_cells)


if __name__ == "__main__":
    main()
